TfLiteStatus OpaqueAddPrepare(TfLiteOpaqueContext* context,
                              TfLiteOpaqueNode* node) {
  const TfLiteOpaqueTensor* input1 = TfLiteOpaqueNodeGetInput(context, node, 0);
  TfLiteOpaqueTensor* output = TfLiteOpaqueNodeGetOutput(context, node, 0);
  int num_dims = TfLiteOpaqueTensorNumDims(input1);
  TfLiteIntArray* dims = TfLiteIntArrayCreate(num_dims);
  for (int i = 0; i < num_dims; ++i) {
    dims->data[i] = TfLiteOpaqueTensorDim(input1, i);
  }
  return TfLiteOpaqueContextResizeTensor(context, output, dims);
}

TfLiteStatus OpaqueAddInvoke(TfLiteOpaqueContext* context,
                             TfLiteOpaqueNode* node) {
  const TfLiteOpaqueTensor* input1 = TfLiteOpaqueNodeGetInput(context, node, 0);
  const TfLiteOpaqueTensor* input2 = TfLiteOpaqueNodeGetInput(context, node, 1);
  TfLiteOpaqueTensor* output = TfLiteOpaqueNodeGetOutput(context, node, 0);

  const float* in1 = static_cast<const float*>(TfLiteOpaqueTensorData(input1));
  const float* in2 = static_cast<const float*>(TfLiteOpaqueTensorData(input2));
  float* out = static_cast<float*>(TfLiteOpaqueTensorData(output));
  size_t count = TfLiteOpaqueTensorByteSize(input1) / sizeof(float);
  for (size_t i = 0; i < count; ++i) {
    out[i] = in1[i] + in2[i];
  }
  return kTfLiteOk;
}

TfLiteStatus OpaqueMulInvoke(TfLiteOpaqueContext* context,
                             TfLiteOpaqueNode* node) {
  const TfLiteOpaqueTensor* input1 = TfLiteOpaqueNodeGetInput(context, node, 0);
  const TfLiteOpaqueTensor* input2 = TfLiteOpaqueNodeGetInput(context, node, 1);
  TfLiteOpaqueTensor* output = TfLiteOpaqueNodeGetOutput(context, node, 0);

  const float* in1 = static_cast<const float*>(TfLiteOpaqueTensorData(input1));
  const float* in2 = static_cast<const float*>(TfLiteOpaqueTensorData(input2));
  float* out = static_cast<float*>(TfLiteOpaqueTensorData(output));
  size_t count = TfLiteOpaqueTensorByteSize(input1) / sizeof(float);
  for (size_t i = 0; i < count; ++i) {
    out[i] = in1[i] * in2[i];
  }
  return kTfLiteOk;
}

// Builds an in-memory hybrid model computing `MyCustomOp(ADD(x, y), y)`.
Expected<flatbuffers::DetachedBuffer> BuildHybridAddAndCustomOpModel() {
  std::ifstream input_file(testing::GetTestFilePath(kModelFileName),
                           std::ios::binary);
  if (!input_file.is_open()) {
    return Unexpected(Status::kErrorNotFound,
                      "Failed to open simple_model.tflite");
  }
  const std::string original_model((std::istreambuf_iterator<char>(input_file)),
                                   std::istreambuf_iterator<char>());

  std::unique_ptr<tflite::ModelT> tfl_model =
      tflite::UnPackModel(original_model.data());
  if (tfl_model == nullptr || tfl_model->subgraphs.size() != 1 ||
      tfl_model->subgraphs[0]->inputs.size() != 2 ||
      tfl_model->subgraphs[0]->outputs.size() != 1) {
    return Unexpected(Status::kErrorInvalidArgument,
                      "Unexpected simple_model.tflite structure");
  }
  tflite::SubGraphT& subgraph = *tfl_model->subgraphs[0];
  const int32_t add_out_idx = subgraph.outputs[0];

  const uint32_t new_buf_idx = static_cast<uint32_t>(tfl_model->buffers.size());
  tfl_model->buffers.push_back(std::make_unique<tflite::BufferT>());

  auto final_out =
      std::make_unique<tflite::TensorT>(*subgraph.tensors[add_out_idx]);
  final_out->name = "final_out";
  final_out->buffer = new_buf_idx;
  const int32_t final_out_idx = static_cast<int32_t>(subgraph.tensors.size());
  subgraph.tensors.push_back(std::move(final_out));

  auto custom_code = std::make_unique<tflite::OperatorCodeT>();
  custom_code->deprecated_builtin_code = tflite::BuiltinOperator_CUSTOM;
  custom_code->builtin_code = tflite::BuiltinOperator_CUSTOM;
  custom_code->custom_code = "MyCustomOp";
  custom_code->version = 1;
  const uint32_t custom_opcode_idx =
      static_cast<uint32_t>(tfl_model->operator_codes.size());
  tfl_model->operator_codes.push_back(std::move(custom_code));

  auto custom_op = std::make_unique<tflite::OperatorT>();
  custom_op->opcode_index = custom_opcode_idx;
  custom_op->inputs = {add_out_idx, subgraph.inputs[1]};
  custom_op->outputs = {final_out_idx};
  subgraph.operators.push_back(std::move(custom_op));

  subgraph.outputs[0] = final_out_idx;
  for (auto& sig : tfl_model->signature_defs) {
    for (auto& out_map : sig->outputs) {
      if (out_map->tensor_index == static_cast<uint32_t>(add_out_idx)) {
        out_map->tensor_index = static_cast<uint32_t>(final_out_idx);
      }
    }
  }

  flatbuffers::FlatBufferBuilder builder;
  tflite::FinishModelBuffer(builder,
                            tflite::Model::Pack(builder, tfl_model.get()));
  return builder.Release();
}
