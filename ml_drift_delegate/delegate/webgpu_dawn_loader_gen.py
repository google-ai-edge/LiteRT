"""Generates C++ DawnProcTable dynamic symbol population for libdawn_proc."""

import argparse
import pathlib
import re

_CORE_REQUIRED_PROCS = (
    "createInstance",
    "instanceRequestAdapter",
    "adapterRequestDevice",
    "deviceCreateShaderModule",
    "deviceCreateComputePipeline",
    "deviceCreateBuffer",
    "deviceGetQueue",
)

_PROC_FIELD_RE = re.compile(
    r"\bWGPUProc([A-Za-z0-9_]+)\s+([A-Za-z0-9_]+)\s*(?:=\s*nullptr)?\s*;"
)


def _parse_proc_table(proc_table_text: str) -> list[tuple[str, str]]:
  entries = _PROC_FIELD_RE.findall(proc_table_text)
  if not entries:
    raise ValueError("No WGPUProc fields found in dawn_proc_table.h")
  return entries


def _generate_inc(procs: list[tuple[str, str]]) -> str:
  """Renders the C++ .inc fragment (intentionally free of #include lines)."""
  proc_field_names = {camel for _, camel in procs}
  for required in _CORE_REQUIRED_PROCS:
    if required not in proc_field_names:
      raise ValueError(
          f"Core required proc {required!r} not present in DawnProcTable"
      )

  lines: list[str] = [
      "// Generated by webgpu_dawn_loader_gen.py. DO NOT EDIT.",
      "",
      "namespace litert::ml_drift::internal_dawn_loader {",
      "",
      "using SymbolResolver = void* (*)(const char* symbol_name, void* data);",
      "",
      "bool PopulateDawnProcTable(SymbolResolver resolve, void* data,",
      "                           const char** missing_core_symbol) {",
      "  DawnProcTable table = {};",
      "  std::copy_n(dawnProcGetVersion(), sizeof(table.version),",
      "              table.version);",
  ]

  for pascal_name, camel_name in procs:
    c_name = f"wgpu{pascal_name}"
    lines.append(
        f"  table.{camel_name} = reinterpret_cast<WGPUProc{pascal_name}>("
        f'resolve("{c_name}", data));'
    )

  for required in _CORE_REQUIRED_PROCS:
    req_c_name = f"wgpu{required[0].upper()}{required[1:]}"
    lines.append(f"  if (table.{required} == nullptr) {{")
    lines.append("    if (missing_core_symbol != nullptr) {")
    lines.append(f'      *missing_core_symbol = "{req_c_name}";')
    lines.append("    }")
    lines.append("    return false;")
    lines.append("  }")

  lines.extend([
      "  dawnProcSetProcs(&table);",
      "  return true;",
      "}",
      "",
      "}  // namespace litert::ml_drift::internal_dawn_loader",
      "",
  ])
  return "\n".join(lines)


def main() -> None:
  parser = argparse.ArgumentParser()
  parser.add_argument("--proc_table_header", required=True, type=pathlib.Path)
  parser.add_argument("--output", required=True, type=pathlib.Path)
  args = parser.parse_args()

  procs = _parse_proc_table(args.proc_table_header.read_text(encoding="utf-8"))
  args.output.write_text(_generate_inc(procs), encoding="utf-8")


if __name__ == "__main__":
  main()
